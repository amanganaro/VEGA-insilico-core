package golden;

import insilico.core.molecule.InsilicoMolecule;
import insilico.core.molecule.conversion.SmilesMolecule;
import insilico.core.similarity.SimilarityDescriptorsBuilder;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfSystemProperty;
import org.openscience.cdk.fingerprint.ExtendedFingerprinter;
import org.openscience.cdk.interfaces.IAtomContainer;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.DirectoryStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.BitSet;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Objects;
import java.util.Random;
import java.util.Set;
import java.util.TreeSet;
import java.util.stream.IntStream;

/**
 * Builds the golden dataset ({@code molecules.tsv}) by merging three sources:
 * <ol>
 *     <li><b>BENCH</b>: benchmark molecules in {@code golden/benchmark.tsv}; they are (re)imported from a plain
 *     SMILES file with {@code -Dgolden.benchmark=<path>}, optionally only some lines with
 *     {@code -Dgolden.benchmark-lines=32-35,62-100};</li>
 *     <li><b>CUR</b>: hand-curated edge cases in {@code golden/curated.tsv};</li>
 *     <li><b>TS</b>: a MaxMin sample of the VEGA training sets (the most diverse molecules, mostly unusual ones),
 *     plus <b>TSR</b>: a random sample of the remaining ones (typical molecules), both stored in
 *     {@code golden/training-sample.tsv}.</li>
 * </ol>
 * The training set sample is computed only if its file does not exist yet, or with {@code -Dgolden.resample=true};
 * the training sets folder is given with {@code -Dgolden.training-sets=<dir>} (default {@code ../training_sets}).
 * <p>
 * Run with: {@code mvn test -Pgolden -Dgolden.build-dataset=true -Dtest=DatasetBuilder}
 */
@Tag("golden")
@EnabledIfSystemProperty(named = "golden.build-dataset", matches = "true")
class DatasetBuilder {

    static final Path CURATED_FILE = GoldenDataset.GOLDEN_DIR.resolve("curated.tsv");
    static final Path BENCHMARK_FILE = GoldenDataset.GOLDEN_DIR.resolve("benchmark.tsv");
    static final Path SAMPLE_FILE = GoldenDataset.GOLDEN_DIR.resolve("training-sample.tsv");

    /** Number of molecules picked from the training sets with MaxMin. */
    private static final int MAXMIN_SIZE = Integer.getInteger("golden.maxmin-size", 250);

    /** Number of molecules picked at random from the training sets (after the MaxMin picks). */
    private static final int RANDOM_SIZE = Integer.getInteger("golden.random-size", 100);

    /** Molecules with more heavy atoms are not sampled, to keep the test run time bounded. */
    private static final int MAX_HEAVY_ATOMS = 150;

    /** Fixed seed: the first MaxMin pick is random, the rest is deterministic. */
    private static final long SEED = 20261111L;

    @Test
    void buildDataset() throws Exception {
        List<GoldenDataset.Entry> all = new ArrayList<>();
        all.addAll(benchmark());
        all.addAll(GoldenDataset.readEntries(CURATED_FILE));
        all.addAll(trainingSample());

        Set<String> names = new HashSet<>();
        for (GoldenDataset.Entry e : all)
            if (!names.add(e.name()))
                throw new IllegalStateException("Duplicated NAME in dataset: " + e.name());

        GoldenDataset.writeEntries(GoldenDataset.MOLECULES_FILE, List.of(
                "Golden regression dataset, generated by golden.DatasetBuilder on " + LocalDate.now(),
                "Do not edit by hand: edit curated.tsv (or the benchmark / training sets) and rebuild."), all);
        System.out.printf("Dataset written: %s (%d molecules)%n", GoldenDataset.MOLECULES_FILE, all.size());
    }

    /**
     * Returns the benchmark molecules (source A) from {@code golden/benchmark.tsv}. If {@code -Dgolden.benchmark}
     * is given, the selected lines of that file are imported first, replacing {@code benchmark.tsv}.
     */
    private static List<GoldenDataset.Entry> benchmark() throws IOException {
        String path = System.getProperty("golden.benchmark");
        if (path != null && !path.isBlank())
            importBenchmark(Path.of(path), System.getProperty("golden.benchmark-lines", ""));
        if (!Files.exists(BENCHMARK_FILE)) {
            System.out.println("WARNING: " + BENCHMARK_FILE + " not found, benchmark molecules skipped");
            return List.of();
        }
        return GoldenDataset.readEntries(BENCHMARK_FILE);
    }

    /**
     * Imports a benchmark file (one SMILES per line) into {@code benchmark.tsv}. NAME is {@code BENCH-<line>}, so
     * names stay stable whatever subset is selected.
     *
     * @param file benchmark file
     * @param lineSelection 1-based line numbers and ranges, e.g. {@code "32-35,39,62-100"}; empty = all lines
     */
    private static void importBenchmark(Path file, String lineSelection) throws IOException {
        Set<Integer> selected = parseLineSelection(lineSelection);
        List<String> lines = Files.readAllLines(file, StandardCharsets.UTF_8);
        List<GoldenDataset.Entry> entries = new ArrayList<>();
        for (int i = 0; i < lines.size(); i++) {
            int lineNumber = i + 1;
            String smiles = lines.get(i).split("\t", -1)[0].trim();
            if (smiles.isEmpty() || smiles.startsWith("#") || (!selected.isEmpty() && !selected.contains(lineNumber)))
                continue;
            entries.add(new GoldenDataset.Entry(String.format(Locale.ROOT, "BENCH-%03d", lineNumber), smiles,
                    "benchmark:" + file.getFileName(), "benchmark"));
        }
        GoldenDataset.writeEntries(BENCHMARK_FILE, List.of(
                "Molecules imported from " + file.getFileName() + " on " + LocalDate.now()
                        + (lineSelection.isBlank() ? "" : ", lines " + lineSelection),
                "NAME = BENCH-<line number in the original file>"), entries);
    }

    private static Set<Integer> parseLineSelection(String selection) {
        Set<Integer> result = new TreeSet<>();
        for (String part : selection.split(",")) {
            part = part.trim();
            if (part.isEmpty())
                continue;
            String[] range = part.split("-");
            int from = Integer.parseInt(range[0].trim());
            int to = range.length > 1 ? Integer.parseInt(range[1].trim()) : from;
            for (int i = from; i <= to; i++)
                result.add(i);
        }
        return result;
    }

    /** Returns the training set sample (source C), computing it if needed. */
    private static List<GoldenDataset.Entry> trainingSample() throws IOException {
        if (Files.exists(SAMPLE_FILE) && !Boolean.getBoolean("golden.resample"))
            return GoldenDataset.readEntries(SAMPLE_FILE);

        Path dir = Path.of(System.getProperty("golden.training-sets", "../training_sets"));
        Map<String, String> smilesToSource = readTrainingSets(dir);
        System.out.printf("Unique input SMILES in training sets: %d%n", smilesToSource.size());

        List<Candidate> candidates = toCandidates(smilesToSource);
        System.out.printf("Valid unique candidates (<= %d heavy atoms): %d%n", MAX_HEAVY_ATOMS, candidates.size());

        List<Candidate> picked = maxMin(candidates, MAXMIN_SIZE);
        List<GoldenDataset.Entry> entries = new ArrayList<>();
        for (int i = 0; i < picked.size(); i++) {
            Candidate c = picked.get(i);
            entries.add(new GoldenDataset.Entry(String.format(Locale.ROOT, "TS-%03d", i + 1), c.smiles(),
                    c.source(), "training-set-maxmin"));
        }

        List<Candidate> remaining = new ArrayList<>(candidates);
        remaining.removeAll(picked);
        java.util.Collections.shuffle(remaining, new Random(SEED));
        List<Candidate> randomPicks = remaining.subList(0, Math.min(RANDOM_SIZE, remaining.size()));
        for (int i = 0; i < randomPicks.size(); i++) {
            Candidate c = randomPicks.get(i);
            entries.add(new GoldenDataset.Entry(String.format(Locale.ROOT, "TSR-%03d", i + 1), c.smiles(),
                    c.source(), "training-set-random"));
        }

        GoldenDataset.writeEntries(SAMPLE_FILE, List.of(
                "Sample of the VEGA training sets, " + LocalDate.now() + ": TS-* MaxMin picks (Tanimoto, CDK "
                        + "extended fingerprint), TSR-* random picks among the rest",
                "Regenerate with -Dgolden.resample=true"), entries);
        return entries;
    }

    /**
     * Reads every {@code ts_*.txt} file and returns the distinct input SMILES with the first file they were found in.
     * The SMILES column is the first header containing "smi" (case insensitive).
     */
    private static Map<String, String> readTrainingSets(Path dir) throws IOException {
        Set<Path> files = new TreeSet<>();
        try (DirectoryStream<Path> ds = Files.newDirectoryStream(dir, "ts_*.txt")) {
            ds.forEach(files::add);
        }
        if (files.isEmpty())
            throw new IllegalStateException("No ts_*.txt files found in " + dir.toAbsolutePath());

        Map<String, String> result = new LinkedHashMap<>();
        for (Path f : files) {
            List<String> lines = Files.readAllLines(f, StandardCharsets.UTF_8);
            if (lines.isEmpty())
                continue;
            String[] header = lines.get(0).split("\t", -1);
            int col = IntStream.range(0, header.length)
                    .filter(i -> header[i].toLowerCase(Locale.ROOT).contains("smi"))
                    .findFirst().orElse(-1);
            if (col < 0) {
                System.out.println("WARNING: no SMILES column in " + f.getFileName());
                continue;
            }
            for (String line : lines.subList(1, lines.size())) {
                String[] fields = line.split("\t", -1);
                if (fields.length <= col)
                    continue;
                String smiles = fields[col].trim();
                // disconnected structures are rejected by the core: useless as regression samples
                if (smiles.isEmpty() || smiles.contains("."))
                    continue;
                result.putIfAbsent(smiles, f.getFileName().toString());
            }
        }
        return result;
    }

    /** A valid, converted training set molecule. */
    private record Candidate(String smiles, String source, String coreSmiles, BitSet fingerprint) { }

    /**
     * Converts the SMILES (in parallel), keeps the valid ones, removes duplicates by the SMILES regenerated by the
     * core and computes the extended fingerprint with the same parameters as {@link SimilarityDescriptorsBuilder}.
     */
    private static List<Candidate> toCandidates(Map<String, String> smilesToSource) {
        List<Map.Entry<String, String>> input = new ArrayList<>(smilesToSource.entrySet());
        ThreadLocal<ExtendedFingerprinter> fingerprinter = ThreadLocal.withInitial(() -> {
            ExtendedFingerprinter fp = new ExtendedFingerprinter(SimilarityDescriptorsBuilder.PARAM_FP_SIZE,
                    SimilarityDescriptorsBuilder.PARAM_FP_DEPTH);
            fp.setHashPseudoAtoms(true);
            return fp;
        });

        List<Candidate> converted = input.parallelStream().map(e -> {
            try {
                InsilicoMolecule mol = SmilesMolecule.Convert(e.getKey());
                if (!mol.IsValid())
                    return null;
                IAtomContainer structure = mol.GetStructure();
                if (structure.getAtomCount() > MAX_HEAVY_ATOMS)
                    return null;
                BitSet fp = fingerprinter.get().getBitFingerprint(structure).asBitSet();
                return new Candidate(e.getKey(), e.getValue(), mol.GetSMILES(), fp);
            } catch (Throwable t) {
                return null;
            }
        }).filter(Objects::nonNull).toList();

        // dedup keeping input order (stream preserves encounter order)
        Set<String> seen = new HashSet<>();
        List<Candidate> unique = new ArrayList<>();
        for (Candidate c : converted)
            if (seen.add(c.coreSmiles()))
                unique.add(c);
        return unique;
    }

    /** Classic MaxMin diversity picking on Tanimoto distance. */
    private static List<Candidate> maxMin(List<Candidate> candidates, int k) {
        int n = candidates.size();
        double[] minDist = new double[n];
        java.util.Arrays.fill(minDist, Double.MAX_VALUE);
        boolean[] taken = new boolean[n];
        List<Candidate> picked = new ArrayList<>();

        int next = new Random(SEED).nextInt(n);
        while (picked.size() < Math.min(k, n)) {
            taken[next] = true;
            Candidate p = candidates.get(next);
            picked.add(p);
            final BitSet pfp = p.fingerprint();
            IntStream.range(0, n).parallel().forEach(i -> {
                if (!taken[i]) {
                    double d = tanimotoDistance(pfp, candidates.get(i).fingerprint());
                    if (d < minDist[i])
                        minDist[i] = d;
                }
            });
            // farthest from the picked set; ties resolved by lowest index (deterministic)
            int best = -1;
            for (int i = 0; i < n; i++)
                if (!taken[i] && (best < 0 || minDist[i] > minDist[best]))
                    best = i;
            if (best < 0)
                break;
            next = best;
        }
        return picked;
    }

    private static double tanimotoDistance(BitSet a, BitSet b) {
        BitSet and = (BitSet) a.clone();
        and.and(b);
        int common = and.cardinality();
        int union = a.cardinality() + b.cardinality() - common;
        return union == 0 ? 0.0 : 1.0 - (double) common / union;
    }
}
