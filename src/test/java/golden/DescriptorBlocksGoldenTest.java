package golden;

import insilico.core.descriptor.DescriptorBlock;
import insilico.core.molecule.InsilicoMolecule;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;

/**
 * Golden regression test of the descriptor blocks: every block is calculated on every molecule of the golden
 * dataset and compared exactly with {@code golden/descriptors-<Block>.tsv}.
 * <p>
 * Invalid molecules are calculated too (they must give MISSING_VALUE). The {@code SMILES_OUT} column (SMILES
 * regenerated by the core) separates changes in how the structure is read from changes in the calculation.
 * <p>
 * Run with {@code mvn test -Pgolden}; regenerate the references with {@code -Dgolden.update=true}.
 */
@Tag("golden")
class DescriptorBlocksGoldenTest {

    static List<GoldenBlocks.Block> blocks() {
        return GoldenBlocks.ALL;
    }

    static Path referenceFile(GoldenBlocks.Block block) {
        return GoldenDataset.GOLDEN_DIR.resolve("descriptors-" + block.name() + ".tsv");
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("blocks")
    void blockMatchesGoldenFile(GoldenBlocks.Block block) throws Exception {
        List<GoldenDataset.Item> items = GoldenDataset.load();

        String[] names = block.factory().get().GetAllNames();
        List<String> header = new ArrayList<>(List.of("ID", "VALID", "SMILES_OUT"));
        header.addAll(Arrays.asList(names));
        GoldenFiles.Table table = new GoldenFiles.Table(header);

        for (GoldenDataset.Item item : items) {
            InsilicoMolecule mol = item.molecule();
            DescriptorBlock db = block.factory().get();
            db.Calculate(mol);
            assertArrayEquals(names, db.GetAllNames(), "descriptor names changed after Calculate for "
                    + item.entry().name());

            List<String> row = new ArrayList<>();
            row.add(Boolean.toString(mol.IsValid()));
            row.add(mol.IsValid() ? mol.GetSMILES() : "");
            for (double v : db.GetAllValues())
                row.add(GoldenFiles.format(v));
            table.addRow(item.entry().name(), row);
        }

        GoldenDiff.check(block.name(), referenceFile(block),
                block.name() + " descriptors on golden/molecules.tsv (generated by DescriptorBlocksGoldenTest)",
                table);
    }
}
