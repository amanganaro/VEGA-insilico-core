package golden;

import insilico.core.descriptor.blocks.FunctionalGroups;
import insilico.core.similarity.Similarity;
import insilico.core.similarity.SimilarityDescriptors;
import insilico.core.similarity.SimilarityDescriptorsBuilder;
import insilico.core.similarity.descriptors.simConstitutional;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.BitSet;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Collectors;

import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Golden regression tests of the similarity, on the valid molecules of the golden dataset.
 * <ul>
 *     <li>{@code golden/similarity-descriptors.tsv}: the content of {@link SimilarityDescriptors} of every molecule
 *     (simConstitutional values, hetero atoms, functional groups, fingerprint bits). When the matrix changes, this
 *     file tells whether the cause is the fingerprint or one of the descriptor arrays.</li>
 *     <li>{@code golden/similarity.tsv}: the similarity matrix, upper triangle only (diagonal included, the cells
 *     below the diagonal are empty). Symmetry of the similarity is not checked.</li>
 * </ul>
 * Default configuration, as in {@code insilicoKnn}: {@code new SimilarityDescriptorsBuilder()} and
 * {@code new Similarity()}, using {@link Similarity#Calculate} (already truncated to 3 decimal digits). A pair whose
 * calculation throws an exception is stored as {@code ERROR:<exception class>}.
 * <p>
 * When the matrix differs, a report of how much the similarity values changed (distribution of |delta|, largest
 * changes, molecules involved most often) is added to the summary and written to
 * {@code target/golden-diff/similarity-delta.txt}. Besides the comparison, every molecule must have similarity 1.0
 * with itself.
 */
@Tag("golden")
class SimilarityMatrixGoldenTest {

    static final Path REFERENCE_FILE = GoldenDataset.GOLDEN_DIR.resolve("similarity.tsv");
    static final Path DESCRIPTORS_REFERENCE_FILE = GoldenDataset.GOLDEN_DIR.resolve("similarity-descriptors.tsv");

    /** Names of the HeteroAtoms array, in the order filled by {@link SimilarityDescriptorsBuilder}. */
    private static final List<String> HETERO_NAMES =
            List.of("nN", "nO", "nP", "nS", "nF", "nCl", "nBr", "nI", "nB", "nHet", "nX");

    /** Cell value used when an array (or the fingerprint) is null or has an unexpected length. */
    private static final String NULL_VALUE = "null";

    /** Similarity change report: number of pairs and molecules listed, and threshold of a "large" change. */
    private static final int TOP_PAIRS = 20;
    private static final int TOP_MOLECULES = 15;
    private static final double LARGE_DELTA = 0.05;

    private static List<GoldenDataset.Item> valid;
    private static List<SimilarityDescriptors> descriptors;

    @BeforeAll
    static void calculateSimilarityDescriptors() throws Exception {
        valid = GoldenDataset.load().stream().filter(i -> i.molecule().IsValid()).toList();
        SimilarityDescriptorsBuilder builder = new SimilarityDescriptorsBuilder();
        descriptors = new ArrayList<>();
        for (GoldenDataset.Item item : valid)
            descriptors.add(builder.Calculate(item.molecule()));
    }

    @Test
    void similarityDescriptorsMatchGoldenFile() throws Exception {
        List<String> constNames = List.of(new simConstitutional().GetAllNames());
        List<String> fgNames = List.of(new FunctionalGroups().GetAllNames());

        List<String> header = new ArrayList<>();
        header.add("ID");
        constNames.forEach(n -> header.add("CONST_" + n));
        HETERO_NAMES.forEach(n -> header.add("HET_" + n));
        fgNames.forEach(n -> header.add("FG_" + n));
        header.add("FP_CARDINALITY");
        header.add("FP_BITS");
        GoldenFiles.Table table = new GoldenFiles.Table(header);

        for (int i = 0; i < valid.size(); i++) {
            SimilarityDescriptors d = descriptors.get(i);
            List<String> row = new ArrayList<>();
            addArray(row, d.Constitutional, constNames.size());
            addArray(row, d.HeteroAtoms, HETERO_NAMES.size());
            addArray(row, d.FunctionalGroups, fgNames.size());
            addFingerprint(row, d.Fingerprint);
            table.addRow(valid.get(i).entry().name(), row);
        }

        GoldenDiff.check("similarity-descriptors", DESCRIPTORS_REFERENCE_FILE,
                "SimilarityDescriptors of the valid molecules of golden/molecules.tsv "
                        + "(generated by SimilarityMatrixGoldenTest)", table);
    }

    @Test
    void similarityMatrixMatchesGoldenFile() throws Exception {
        Similarity similarity = new Similarity();
        int n = valid.size();
        // upper triangle only (diagonal included): the cells below the diagonal are left empty
        String[][] matrix = new String[n][n];
        for (int i = 0; i < n; i++)
            for (int j = 0; j < n; j++)
                matrix[i][j] = j < i ? "" : calculate(similarity, descriptors.get(i), descriptors.get(j));

        // a molecule is identical to itself; calculation errors are already part of the golden comparison
        List<String> wrongDiagonal = new ArrayList<>();
        for (int i = 0; i < n; i++)
            if (!matrix[i][i].equals("1.0") && !matrix[i][i].startsWith("ERROR:"))
                wrongDiagonal.add(valid.get(i).entry().name() + " (" + matrix[i][i] + ")");

        List<String> header = new ArrayList<>();
        header.add("ID");
        valid.forEach(item -> header.add(item.entry().name()));
        GoldenFiles.Table table = new GoldenFiles.Table(header);
        for (int i = 0; i < n; i++)
            table.addRow(valid.get(i).entry().name(), List.of(matrix[i]));

        long pairs = (long) n * (n + 1) / 2;
        GoldenDiff.check("similarity", REFERENCE_FILE,
                "Similarity matrix (upper triangle, diagonal included) of the valid molecules of "
                        + "golden/molecules.tsv (generated by SimilarityMatrixGoldenTest)", table,
                diffs -> similarityDeltaReport(diffs, pairs));

        assertTrue(wrongDiagonal.isEmpty(), "Self-similarity different from 1.0 for " + wrongDiagonal);
    }

    /**
     * Describes how much the similarity values changed, on the pairs present in both the reference and the computed
     * matrix. Pairs with a non-numeric value (empty or {@code ERROR:}) or a missing value (-999) on either side are
     * only counted, never used in the statistics; they are still listed in {@code similarity-diff.tsv}. Molecules are
     * shown as {@code NAME (SMILES)}. The report is also written to
     * {@code target/golden-diff/similarity-delta.txt}.
     *
     * @param diffs changed cells of the matrix (row = first molecule, column = second molecule)
     * @param totalPairs number of pairs in the computed triangle, diagonal included
     * @return the report lines
     */
    private static List<String> similarityDeltaReport(List<GoldenDiff.CellDiff> diffs, long totalPairs) {
        // nothing to report when only rows/columns were added or removed
        if (diffs.isEmpty())
            return List.of();

        record PairDelta(String a, String b, double expected, double actual) {
            double abs() {
                return Math.abs(actual - expected);
            }
        }

        List<PairDelta> deltas = new ArrayList<>();
        int nonNumeric = 0;
        for (GoldenDiff.CellDiff d : diffs) {
            Double e = GoldenDiff.parse(d.expected()), a = GoldenDiff.parse(d.actual());
            if (e == null || a == null || GoldenDiff.isMissing(e) || GoldenDiff.isMissing(a))
                nonNumeric++;
            else
                deltas.add(new PairDelta(d.id(), d.column(), e, a));
        }

        List<String> lines = new ArrayList<>();
        lines.add("--- Similarity change report ---");
        lines.add(String.format(Locale.ROOT,
                "Changed pairs: %d of %d (%.1f%%); changes to/from a non-numeric or missing value: %d",
                deltas.size(), totalPairs, 100.0 * deltas.size() / totalPairs, nonNumeric));
        if (!deltas.isEmpty()) {
            double sum = 0;
            int up = 0;
            for (PairDelta p : deltas) {
                sum += p.abs();
                if (p.actual() > p.expected())
                    up++;
            }
            lines.add(String.format(Locale.ROOT, "Mean |delta| on changed pairs: %.4f; on all pairs: %.4f; "
                            + "increased: %d, decreased: %d",
                    sum / deltas.size(), sum / totalPairs, up, deltas.size() - up));

            double[] limits = {0.001, 0.01, 0.05, 0.1, 0.3};
            String[] labels = {"< 0.001", "0.001 - 0.01", "0.01 - 0.05", "0.05 - 0.1", "0.1 - 0.3", ">= 0.3"};
            int[] counts = new int[labels.length];
            // small tolerance, since the similarity is truncated to 3 decimal digits and parsed back from text
            for (PairDelta p : deltas) {
                int bin = 0;
                while (bin < limits.length && p.abs() >= limits[bin] - 1e-9)
                    bin++;
                counts[bin]++;
            }
            lines.add("|delta|\tPairs");
            for (int i = 0; i < labels.length; i++)
                lines.add(labels[i] + "\t" + counts[i]);

            lines.add("Largest changes (expected -> actual, molecule A, molecule B):");
            deltas.stream()
                    .sorted(Comparator.comparingDouble(PairDelta::abs).reversed())
                    .limit(TOP_PAIRS)
                    .forEach(p -> lines.add(String.format(Locale.ROOT, "  %.3f -> %.3f\t%s\t%s",
                            p.expected(), p.actual(), GoldenDataset.label(p.a()), GoldenDataset.label(p.b()))));

            Map<String, Integer> involvement = new HashMap<>();
            for (PairDelta p : deltas)
                if (p.abs() >= LARGE_DELTA - 1e-9) {
                    involvement.merge(p.a(), 1, Integer::sum);
                    if (!p.b().equals(p.a()))
                        involvement.merge(p.b(), 1, Integer::sum);
                }
            if (!involvement.isEmpty()) {
                lines.add("Molecules in most pairs with |delta| >= " + LARGE_DELTA + ":");
                involvement.entrySet().stream()
                        .sorted(Map.Entry.<String, Integer>comparingByValue().reversed()
                                .thenComparing(Map.Entry.comparingByKey()))
                        .limit(TOP_MOLECULES)
                        .forEach(e -> lines.add("  " + e.getValue() + "\t" + GoldenDataset.label(e.getKey())));
            }
        }
        lines.add("---");

        try {
            Files.write(GoldenDiff.DIFF_DIR.resolve("similarity-delta.txt"), lines, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        return lines;
    }

    private static String calculate(Similarity similarity, SimilarityDescriptors a, SimilarityDescriptors b) {
        try {
            return GoldenFiles.format(similarity.Calculate(a, b));
        } catch (Exception e) {
            return "ERROR:" + e.getClass().getSimpleName();
        }
    }

    /** Appends {@code expectedLength} cells; all {@code null} if the array is missing or has a different length. */
    private static void addArray(List<String> row, double[] values, int expectedLength) {
        boolean usable = values != null && values.length == expectedLength;
        for (int i = 0; i < expectedLength; i++)
            row.add(usable ? GoldenFiles.format(values[i]) : NULL_VALUE);
    }

    /** Appends the number of set bits and their sorted indices (space separated). */
    private static void addFingerprint(List<String> row, BitSet fingerprint) {
        if (fingerprint == null) {
            row.add(NULL_VALUE);
            row.add(NULL_VALUE);
            return;
        }
        row.add(Integer.toString(fingerprint.cardinality()));
        row.add(fingerprint.stream().mapToObj(Integer::toString).collect(Collectors.joining(" ")));
    }
}
