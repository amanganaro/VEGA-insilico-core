package golden;

import insilico.core.descriptor.blocks.FunctionalGroups;
import insilico.core.similarity.Similarity;
import insilico.core.similarity.SimilarityDescriptors;
import insilico.core.similarity.SimilarityDescriptorsBuilder;
import insilico.core.similarity.descriptors.simConstitutional;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.BitSet;
import java.util.List;
import java.util.stream.Collectors;

import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Golden regression tests of the similarity, on the valid molecules of the golden dataset.
 * <ul>
 *     <li>{@code golden/similarity-descriptors.tsv}: the content of {@link SimilarityDescriptors} of every molecule
 *     (simConstitutional values, hetero atoms, functional groups, fingerprint bits). When the matrix changes, this
 *     file tells whether the cause is the fingerprint or one of the descriptor arrays.</li>
 *     <li>{@code golden/similarity.tsv}: the full n&times;n similarity matrix.</li>
 * </ul>
 * Default configuration, as in {@code insilicoKnn}: {@code new SimilarityDescriptorsBuilder()} and
 * {@code new Similarity()}, using {@link Similarity#Calculate} (already truncated to 3 decimal digits). A pair whose
 * calculation throws an exception is stored as {@code ERROR:<exception class>}.
 * <p>
 * Besides the comparison, the matrix must be symmetric and every molecule must have similarity 1.0 with itself.
 */
@Tag("golden")
class SimilarityMatrixGoldenTest {

    static final Path REFERENCE_FILE = GoldenDataset.GOLDEN_DIR.resolve("similarity.tsv");
    static final Path DESCRIPTORS_REFERENCE_FILE = GoldenDataset.GOLDEN_DIR.resolve("similarity-descriptors.tsv");

    /** Names of the HeteroAtoms array, in the order filled by {@link SimilarityDescriptorsBuilder}. */
    private static final List<String> HETERO_NAMES =
            List.of("nN", "nO", "nP", "nS", "nF", "nCl", "nBr", "nI", "nB", "nHet", "nX");

    /** Cell value used when an array (or the fingerprint) is null or has an unexpected length. */
    private static final String NULL_VALUE = "null";

    private static List<GoldenDataset.Item> valid;
    private static List<SimilarityDescriptors> descriptors;

    @BeforeAll
    static void calculateSimilarityDescriptors() throws Exception {
        valid = GoldenDataset.load().stream().filter(i -> i.molecule().IsValid()).toList();
        SimilarityDescriptorsBuilder builder = new SimilarityDescriptorsBuilder();
        descriptors = new ArrayList<>();
        for (GoldenDataset.Item item : valid)
            descriptors.add(builder.Calculate(item.molecule()));
    }

    @Test
    void similarityDescriptorsMatchGoldenFile() throws Exception {
        List<String> constNames = List.of(new simConstitutional().GetAllNames());
        List<String> fgNames = List.of(new FunctionalGroups().GetAllNames());

        List<String> header = new ArrayList<>();
        header.add("ID");
        constNames.forEach(n -> header.add("CONST_" + n));
        HETERO_NAMES.forEach(n -> header.add("HET_" + n));
        fgNames.forEach(n -> header.add("FG_" + n));
        header.add("FP_CARDINALITY");
        header.add("FP_BITS");
        GoldenFiles.Table table = new GoldenFiles.Table(header);

        for (int i = 0; i < valid.size(); i++) {
            SimilarityDescriptors d = descriptors.get(i);
            List<String> row = new ArrayList<>();
            addArray(row, d.Constitutional, constNames.size());
            addArray(row, d.HeteroAtoms, HETERO_NAMES.size());
            addArray(row, d.FunctionalGroups, fgNames.size());
            addFingerprint(row, d.Fingerprint);
            table.addRow(valid.get(i).entry().name(), row);
        }

        GoldenDiff.check("similarity-descriptors", DESCRIPTORS_REFERENCE_FILE,
                "SimilarityDescriptors of the valid molecules of golden/molecules.tsv "
                        + "(generated by SimilarityMatrixGoldenTest)", table);
    }

    @Test
    void similarityMatrixMatchesGoldenFile() throws Exception {
        Similarity similarity = new Similarity();
        int n = valid.size();
        String[][] matrix = new String[n][n];
        for (int i = 0; i < n; i++)
            for (int j = 0; j < n; j++)
                matrix[i][j] = calculate(similarity, descriptors.get(i), descriptors.get(j));

        List<String> asymmetric = new ArrayList<>();
        for (int i = 0; i < n; i++)
            for (int j = i + 1; j < n; j++)
                if (!matrix[i][j].equals(matrix[j][i]))
                    asymmetric.add(valid.get(i).entry().name() + "/" + valid.get(j).entry().name() + " ("
                            + matrix[i][j] + " vs " + matrix[j][i] + ")");

        // a molecule is identical to itself; calculation errors are already part of the golden comparison
        List<String> wrongDiagonal = new ArrayList<>();
        for (int i = 0; i < n; i++)
            if (!matrix[i][i].equals("1.0") && !matrix[i][i].startsWith("ERROR:"))
                wrongDiagonal.add(valid.get(i).entry().name() + " (" + matrix[i][i] + ")");

        List<String> header = new ArrayList<>();
        header.add("ID");
        valid.forEach(item -> header.add(item.entry().name()));
        GoldenFiles.Table table = new GoldenFiles.Table(header);
        for (int i = 0; i < n; i++)
            table.addRow(valid.get(i).entry().name(), List.of(matrix[i]));

        GoldenDiff.check("similarity", REFERENCE_FILE,
                "Full similarity matrix of the valid molecules of golden/molecules.tsv "
                        + "(generated by SimilarityMatrixGoldenTest)", table);

        assertTrue(asymmetric.isEmpty(), "Similarity matrix is not symmetric for " + asymmetric.size()
                + " pairs, e.g. " + asymmetric.subList(0, Math.min(10, asymmetric.size())));
        assertTrue(wrongDiagonal.isEmpty(), "Self-similarity different from 1.0 for " + wrongDiagonal);
    }

    private static String calculate(Similarity similarity, SimilarityDescriptors a, SimilarityDescriptors b) {
        try {
            return GoldenFiles.format(similarity.Calculate(a, b));
        } catch (Exception e) {
            return "ERROR:" + e.getClass().getSimpleName();
        }
    }

    /** Appends {@code expectedLength} cells; all {@code null} if the array is missing or has a different length. */
    private static void addArray(List<String> row, double[] values, int expectedLength) {
        boolean usable = values != null && values.length == expectedLength;
        for (int i = 0; i < expectedLength; i++)
            row.add(usable ? GoldenFiles.format(values[i]) : NULL_VALUE);
    }

    /** Appends the number of set bits and their sorted indices (space separated). */
    private static void addFingerprint(List<String> row, BitSet fingerprint) {
        if (fingerprint == null) {
            row.add(NULL_VALUE);
            row.add(NULL_VALUE);
            return;
        }
        row.add(Integer.toString(fingerprint.cardinality()));
        row.add(fingerprint.stream().mapToObj(Integer::toString).collect(Collectors.joining(" ")));
    }
}
